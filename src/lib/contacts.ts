// 위 4명의 키워드에는 없지만 GWP(복리후생·근무지원·오피스 환경) 영역인 걸 알 수 있는 일반 단어.
// 여기 걸리면 담당자는 특정 못해도 최소한 팀(HR팀 대신 GWP팀)은 정확히 안내할 수 있다.
const GWP_GENERAL_KEYWORDS = [
  "복지", "근무지원", "근무 지원", "임직원 혜택",
  "제메티", "부속의원", "더베이지", "소노",
  "회식", "사내대출", "사업장",
];

// 질문 원문에서 가장 먼저 매칭되는 담당자를 찾는다. 검색된 규정의 제목·키워드·카테고리는 참고하지 않는다 —
// "한도", "시간" 같은 흔한 단어 때문에 엉뚱한 문서(예: 인사 카테고리 문서)가 최고 점수로 잘못 걸려서
// 그 카테고리를 근거로 잘못 라우팅되는 걸 겪었다. 질문 원문의 키워드만으로 판단하는 게 더 안전하다.
// 매칭되는 게 없으면, 복리후생·근무지원 쪽 일반 단어(GWP_GENERAL_KEYWORDS)인지 본 뒤
// 그것도 아니면 순수 인사 제도로 보고 일반 인사팀으로 돌아간다.
export function pickContact(question: string): string {
  for (const route of CONTACT_ROUTES) {
    if (route.keywords.some((keyword) => question.includes(keyword))) {
      return route.name;
    }
  }
  if (GWP_GENERAL_KEYWORDS.some((keyword) => question.includes(keyword))) {
    return DEFAULT_GWP_CONTACT;
  }
  return DEFAULT_CONTACT;
}
